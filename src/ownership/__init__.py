"""Generated package folders, and which generator owns them (ADR-0012).

A generator owns a folder under ``models/<layer>/`` only when the folder holds a README.md
that the generator wrote. It rewrites its folders whole: files it no longer emits are
removed, and a folder it no longer emits is removed with them. It refuses, before writing
anything, any folder it would write that has no README or another generator's.

A generator can also own a region of a hand-written file: the text between a begin and an
end marker, HTML comments the file's author placed once. It rewrites only that text.

With ``--check`` it writes nothing and reports the same changes as drift, byte for byte.
"""

from __future__ import annotations

import difflib
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

MODELS = Path("models")
MARKER = "README.md"


class Refused(Exception):
    """A folder the generator would write belongs to someone else, or a region it owns is broken."""


def marker(generator: str, source: str) -> str:
    return (
        f"# Generated by `uv run {generator} generate`\n"
        "\n"
        f"Written from {source}. Do not edit anything in this folder: the generator rewrites it\n"
        "whole on every run and removes any file it did not write. Change the declarations\n"
        "and run `task generate` instead.\n"
    )


def owner(folder: Path) -> str | None:
    """The generator named by ``folder``'s README, or None when it has no marker."""
    readme = folder / MARKER
    if not readme.is_file():
        return None
    first = readme.read_bytes().decode("utf-8", errors="replace").splitlines()[:1]
    prefix, suffix = "# Generated by `uv run ", " generate`"
    if first and first[0].startswith(prefix) and first[0].endswith(suffix):
        return first[0][len(prefix) : -len(suffix)]
    return None


def owned(root: Path, generator: str) -> set[Path]:
    """Every package folder under models/ that ``generator`` owns."""
    return {
        readme.parent.relative_to(root)
        for readme in (root / MODELS).glob(f"*/*/{MARKER}")
        if owner(readme.parent) == generator
    }


@dataclass(frozen=True)
class Drift:
    """One path where the committed tree differs from what the generator writes.

    ``changed`` carries both sides, ``missing`` the text the generator writes, ``stale`` neither.
    """

    kind: str  # changed | missing | stale
    path: Path  # relative to the repo root
    committed: bytes | None = None
    generated: str | None = None


def _marker(family: str, name: str, side: str) -> re.Pattern:
    """An HTML comment naming ``<family>:<name> <side>``; the rest of the comment is the author's."""
    inside = r"(?:(?!-->).)*?"
    return re.compile(rf"<!--{inside}\b{re.escape(family)}:{name}\s+{side}\b{inside}-->", re.DOTALL)


def _spliced(root: Path, file: Path, regions: dict[str, str]) -> tuple[bytes, str]:
    """``file`` as committed, and as it reads with each region's text between its markers.

    A region is named ``<family>:<name>``. Raises Refused for a missing file or a broken region:
    a marker missing or repeated, an end before its begin, or a marker of the same family inside.
    """
    path = root / file
    if not path.is_file():
        raise Refused(f"{file.as_posix()}: missing")
    committed = path.read_bytes()
    text = committed.decode("utf-8")
    for region, generated in regions.items():
        family, name = region.split(":", 1)
        found = {}
        for side in ("begin", "end"):
            matches = list(_marker(family, re.escape(name), side).finditer(text))
            if len(matches) != 1:
                problem = "missing" if not matches else f"appears {len(matches)} times"
                raise Refused(f"{file.as_posix()}: {region} {side} {problem}")
            found[side] = matches[0]
        begin, end = found["begin"], found["end"]
        if end.start() < begin.end():
            raise Refused(f"{file.as_posix()}: {region} ends before it begins")
        held = text[begin.end() : end.start()]
        for side in ("begin", "end"):
            if foreign := _marker(family, r"[\w-]+", side).search(held):
                raise Refused(f"{file.as_posix()}: {region} holds another marker, {foreign.group(0)}")
        text = text[: begin.end()] + generated + text[end.start() :]
    return committed, text


def drift(
    root: Path,
    generator: str,
    source: str,
    packages: dict[Path, dict[str, str]],
    regions: dict[Path, dict[str, str]] | None = None,
) -> list[Drift]:
    """Every byte ``generator`` would change to make ``packages`` and ``regions`` what it owns.

    ``regions`` maps a hand-written file to the text of each region it owns there.
    Raises Refused, before anything else, for a folder it would write but does not own,
    and for a file whose regions are broken.
    """
    refused = [
        f"{folder} ({'no marker' if owner(root / folder) is None else 'owned by ' + owner(root / folder)})"
        for folder in sorted(packages)
        if (root / folder).exists() and owner(root / folder) != generator
    ]
    if refused:
        raise Refused(f"{generator} does not own: " + ", ".join(refused))
    spliced = {file: _spliced(root, file, owned) for file, owned in sorted((regions or {}).items())}

    found = [Drift("stale", folder) for folder in sorted(owned(root, generator) - set(packages))]
    readme = marker(generator, source)
    for folder, files in sorted(packages.items()):
        wanted = {MARKER: readme, **files}
        if (root / folder).is_dir():
            for existing in sorted((root / folder).iterdir()):
                if existing.name not in wanted:
                    found.append(Drift("stale", folder / existing.name))
        for name, text in sorted(wanted.items()):
            target = root / folder / name
            if not target.is_file():
                found.append(Drift("missing", folder / name, generated=text))
            elif (committed := target.read_bytes()) != text.encode("utf-8"):
                found.append(Drift("changed", folder / name, committed=committed, generated=text))
    for file, (committed, text) in spliced.items():
        if committed != text.encode("utf-8"):
            found.append(Drift("changed", file, committed=committed, generated=text))
    return sorted(found, key=lambda d: d.path.as_posix())


def apply(root: Path, drifts: list[Drift]) -> None:
    """Remove every stale path and write every changed or missing file."""
    for d in drifts:
        target = root / d.path
        if d.kind == "stale":
            shutil.rmtree(target) if target.is_dir() else target.unlink()
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(d.generated.encode("utf-8"))


DIFF_LINES = 40


def _trailing_newlines(text: str) -> int:
    return len(text) - len(text.rstrip("\n"))


def describe(drifts: list[Drift]) -> str:
    """The --check report: a line per drifted path, a capped diff under each changed file, a summary."""
    out = []
    for d in drifts:
        out.append(f"{d.kind} {d.path.as_posix()}")
        if d.kind != "changed":
            continue
        try:
            committed = d.committed.decode("utf-8")
        except UnicodeDecodeError:
            out.append("binary file, no diff shown")
            continue
        if "\r" in committed and "\r" not in d.generated:
            endings = "CRLF" if "\r\n" in committed else "CR"
            out.append(f"line endings differ: the committed file has {endings}, the generator writes LF")
            committed = committed.replace("\r\n", "\n").replace("\r", "\n")
        if _trailing_newlines(committed) != _trailing_newlines(d.generated):
            out.append("the newlines at the end of the file differ")
        if committed.rstrip("\n") == d.generated.rstrip("\n"):
            continue
        lines = [
            line.rstrip("\n")
            for line in difflib.unified_diff(
                committed.splitlines(keepends=True),
                d.generated.splitlines(keepends=True),
                fromfile=f"committed/{d.path.as_posix()}",
                tofile=f"generated/{d.path.as_posix()}",
            )
        ]
        out.extend(lines[:DIFF_LINES])
        if len(lines) > DIFF_LINES:
            out.append(f"({len(lines) - DIFF_LINES} more diff lines left out)")
    paths = "path differs" if len(drifts) == 1 else "paths differ"
    out.append(f"{len(drifts)} {paths} from the declarations; run `task generate`")
    return "\n".join(out)


def run(
    generator: str,
    source: str,
    packages: dict[Path, dict[str, str]],
    regions: dict[Path, dict[str, str]] | None = None,
    *,
    check: bool = False,
) -> int:
    """Write ``packages`` and ``regions`` from the current directory, or with ``check`` report
    what writing would change.

    Exit codes: 0 written or clean; 1 drift found by ``check``; 2 a refused folder or a broken
    region, so a check tells broken input apart from drift.
    """
    root = Path.cwd()
    try:
        drifts = drift(root, generator, source, packages, regions)
    except Refused as refusal:
        print(refusal, file=sys.stderr)
        return 2
    if not check:
        apply(root, drifts)
        return 0
    if not drifts:
        return 0
    print(describe(drifts))
    return 1
