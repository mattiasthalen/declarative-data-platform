"""Generated package folders, and which generator owns them (ADR-0012).

A generator owns a folder under ``models/<layer>/`` only when the folder holds a README.md
that the generator wrote. It rewrites its folders whole: files it no longer emits are
removed, and a folder it no longer emits is removed with them. It refuses, before writing
anything, any folder it would write that has no README or another generator's.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

MODELS = Path("models")
MARKER = "README.md"


class Refused(Exception):
    """A folder the generator would write belongs to someone else."""


def marker(generator: str, source: str) -> str:
    return (
        f"# Generated by `uv run {generator} generate`\n"
        "\n"
        f"Written from {source}. Do not edit anything in this folder: the generator rewrites it\n"
        "whole on every run and removes any file it did not write. Change the declarations\n"
        "and run `task generate` instead.\n"
    )


def owner(folder: Path) -> str | None:
    """The generator named by ``folder``'s README, or None when it has no marker."""
    readme = folder / MARKER
    if not readme.is_file():
        return None
    first = readme.read_text(encoding="utf-8").splitlines()[:1]
    prefix, suffix = "# Generated by `uv run ", " generate`"
    if first and first[0].startswith(prefix) and first[0].endswith(suffix):
        return first[0][len(prefix) : -len(suffix)]
    return None


def owned(root: Path, generator: str) -> set[Path]:
    """Every package folder under models/ that ``generator`` owns."""
    return {
        readme.parent.relative_to(root)
        for readme in (root / MODELS).glob(f"*/*/{MARKER}")
        if owner(readme.parent) == generator
    }


def write(root: Path, generator: str, source: str, packages: dict[Path, dict[str, str]]) -> None:
    """Make ``packages`` (folder -> file name -> text) exactly what ``generator`` owns under models/."""
    refused = [
        f"{folder} ({'no marker' if owner(root / folder) is None else 'owned by ' + owner(root / folder)})"
        for folder in sorted(packages)
        if (root / folder).exists() and owner(root / folder) != generator
    ]
    if refused:
        raise Refused(f"{generator} does not own: " + ", ".join(refused))

    for folder in sorted(owned(root, generator) - set(packages)):
        shutil.rmtree(root / folder)

    readme = marker(generator, source)
    for folder, files in sorted(packages.items()):
        path = root / folder
        path.mkdir(parents=True, exist_ok=True)
        wanted = {MARKER: readme, **files}
        for existing in path.iterdir():
            if existing.name not in wanted:
                shutil.rmtree(existing) if existing.is_dir() else existing.unlink()
        for name, text in sorted(wanted.items()):
            target = path / name
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                target.write_text(text, encoding="utf-8")


def run(generator: str, source: str, packages: dict[Path, dict[str, str]]) -> int:
    """Write ``packages`` from the current directory; report a refusal and return the exit code."""
    try:
        write(Path.cwd(), generator, source, packages)
    except Refused as refusal:
        print(refusal, file=sys.stderr)
        return 1
    return 0
