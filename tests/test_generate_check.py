def test_extra_file_in_generated_folder_is_stale(ws):
    """AC3: an extra file in a generated folder is reported `stale <path>`, exit 1."""
    extra = owned_folders(ws, "conform")[0] / "zz_extra.sql"
    extra.write_text("select 1 as extra\n", encoding="utf-8")
    step = check(ws, "conform")
    drifted(step, "conform")
    assert report(ws, step) == {("stale", rel(ws, extra))}, step.output[-3000:]


def test_folder_no_longer_produced_is_stale(ws):
    """AC3: a marked folder the declarations no longer produce is reported `stale <folder>`, exit 1."""
    marked = owned_folders(ws, "conform")[0]
    retired = marked.parent / "zz_retired"
    retired.mkdir()
    shutil.copyfile(marked / "README.md", retired / "README.md")
    (retired / "zz_retired.sql").write_text("select 1 as retired\n", encoding="utf-8")
    step = check(ws, "conform")
    drifted(step, "conform")
    found = report(ws, step)
    folder = rel(ws, retired)
    assert ("stale", folder) in found, step.output[-3000:]
    assert all(kind == "stale" and (p == folder or p.startswith(folder + "/")) for kind, p in found), (
        step.output[-3000:]
    )


def test_hand_written_sql_in_integrate_folder_is_stale(ws):
    """EC1: a hand-written .sql dropped into integrate's folder is stale, since generate would delete it."""
