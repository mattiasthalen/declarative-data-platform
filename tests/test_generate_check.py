# --------------------------------------------------------------------------- AC8


def test_long_diff_is_capped(ws):
    """AC8: the diff under a file with 200 changed lines is cut at about 40 lines and says how many it left out."""
    target = generated_file(ws, "conform")
    target.write_text("".join(f"select {i} as hand_{i}\n" for i in range(200)), encoding="utf-8")
    step = check(ws, "conform")
    drifted(step, "conform")
    lines = section(step, ws, rel(ws, target))
    assert len(lines) <= 50, f"the diff runs {len(lines)} lines:\n" + "\n".join(lines)
    left_out = [
        line
        for line in lines[1:]
        if not line.startswith(("+", "-", " ", "@"))
        and any(int(n) >= 100 for n in re.findall(r"\d+", line))
    ]
    assert left_out, "no line says how many diff lines were left out:\n" + "\n".join(lines)


