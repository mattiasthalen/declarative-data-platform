def test_hand_written_folders_are_never_read(ws):
    """EC2: files in folders without a generator README, one with a README of its own, fail no check."""
    plain = ws.root / "models" / "conform" / "hand_written"
    plain.mkdir()
    (plain / "my_model.sql").write_text("select 1 as mine\n", encoding="utf-8")
    noted = ws.root / "models" / "integrate" / "notes"
    noted.mkdir()
    (noted / "README.md").write_text("# Notes\n\nWritten by hand.\n", encoding="utf-8")
    (noted / "my_view.sql").write_text("select 2 as mine\n", encoding="utf-8")
    for layer in LAYERS:
        clean(check(ws, layer), layer)
    (plain / "my_model.sql").write_text("select 3 as edited\n", encoding="utf-8")
    for layer in LAYERS:
        clean(check(ws, layer), layer)


def test_deleted_folder_reports_every_file_missing(ws):
    """EC3: models/serve/uss deleted whole is reported as every file in it `missing`."""
    folder = ws.root / "models" / "serve" / "uss"
    files = {rel(ws, p) for p in folder.rglob("*") if p.is_file()}
    assert files, "models/serve/uss holds no file"
    shutil.rmtree(folder)
    step = check(ws, "serve")
    drifted(step, "serve")
    found = report(ws, step)
    assert files <= paths(found, "missing"), f"not reported missing: {files - paths(found, 'missing')}"
    prefix = rel(ws, folder)
    assert all(p == prefix or p.startswith(prefix + "/") for p in paths(found)), step.output[-3000:]


def test_crlf_line_endings_are_drift(ws):
    """EC4: a generated file with CRLF line endings, otherwise identical, is `changed`."""
    target = generated_file(ws, "conform")
    target.write_bytes(target.read_bytes().replace(b"\n", b"\r\n"))
    step = check(ws, "conform")
    drifted(step, "conform")
    assert report(ws, step) == {("changed", rel(ws, target))}, step.output[-3000:]


INVALID_UTF8 = b"\xff\xfe\x80 not utf-8 \xc3\x28\n"


def test_undecodable_generated_file_is_changed_binary(ws):
    """EC5: a generated file holding invalid UTF-8 is `changed`, with "binary" in place of a diff, no crash."""
    target = generated_file(ws, "conform")
    target.write_bytes(target.read_bytes() + INVALID_UTF8)
    step = check(ws, "conform")
    drifted(step, "conform")
    assert report(ws, step) == {("changed", rel(ws, target))}, step.output[-3000:]
    lines = section(step, ws, rel(ws, target))
    assert any("binary" in line.lower() for line in lines), "\n".join(lines)


def test_undecodable_stray_file_is_stale(ws):
    """EC5: a stray file of invalid UTF-8 in an owned folder is `stale`, no crash."""
    stray = owned_folders(ws, "conform")[0] / "zz_blob.bin"
