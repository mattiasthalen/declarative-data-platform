@pytest.mark.parametrize("layer", LAYERS)
def test_hand_edit_is_changed_with_its_diff(ws, layer):
    """AC1: a hand edit to one generated file: exit 1, `changed <path>` for it alone, a diff with the edit."""
    target = generated_file(ws, layer)
    edit_by_hand(target)
    step = check(ws, layer)
    drifted(step, layer)
    assert report(ws, step) == {("changed", rel(ws, target))}, step.output[-3000:]
    diff = section(step, ws, rel(ws, target))
    assert any(line.startswith(("+", "-")) and EDIT_MARK in line for line in diff), (
        f"the diff under {rel(ws, target)} does not show the edit:\n" + "\n".join(diff)
    )
    summary_names_generate(step)


