def test_check_writes_nothing(ws):
    """AC6: on a drifted tree every check leaves the tree byte-identical."""
    edit_by_hand(generated_file(ws, "conform"))
    generated_file(ws, "integrate").unlink()
    (owned_folders(ws, "serve")[0] / "zz_extra.sql").write_text("select 1\n", encoding="utf-8")
    marked = owned_folders(ws, "conform")[0]
    retired = marked.parent / "zz_retired"
    retired.mkdir()
    shutil.copyfile(marked / "README.md", retired / "README.md")
    shutil.rmtree(owned_folders(ws, "serve")[-1])
    before = snapshot(ws)
    for layer in LAYERS:
        drifted(check(ws, layer), layer)
        assert snapshot(ws) == before, f"{layer} generate --check changed the tree"
    task_check(ws)
    assert snapshot(ws) == before, "task check changed the tree"


