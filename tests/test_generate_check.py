def _same_error_as_generate(ws: Workspace, layer: str) -> None:
    checked = check(ws, layer)
    generated = ws.run("uv", "run", layer, "generate")
    message = generated.output.strip()
    assert generated.returncode != 0 and message, f"{layer} generate accepted it:\n{generated.output}"
    assert checked.returncode == 2, f"expected exit 2, got {checked.returncode}:\n{checked.output[-3000:]}"
    assert message in checked.output, (
        f"--check did not print generate's message.\ngenerate:\n{message}\n--check:\n{checked.output[-3000:]}"
    )
    assert "Traceback" not in checked.output, checked.output[-3000:]


