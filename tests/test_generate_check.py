"""`generate --check` and `task check` report drift and write nothing (story 2, D1: AC1-AC9, EC1-EC7).

Each test runs the generators as subprocesses, ``uv run <layer> generate --check`` or
``uv run task check``, in one shared copy of the repo, without a dbt build. The copy's
declarations and models are put back before every test.

The report's interface, as the spec fixes it: one line per drifted path, ``changed <path>``,
``missing <path>`` or ``stale <path>``, with the path relative to the repo root; a unified
diff under a changed file, cut at about 40 lines; a summary naming ``task generate``. Exit 0
and no output when clean, 1 on drift, 2 on an invalid declaration or a refused folder.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

import pytest
import yaml

from harness import Step, Workspace, require

LAYERS = ("conform", "integrate", "serve")
RESTORED = ("models", "contracts", "anchor")
STATUS = re.compile(r"^(changed|missing|stale)\s+(\S+)")
EDIT_MARK = "hand edit 7f3a9c"


@pytest.fixture(scope="module")
def shared(make_workspace, tmp_path_factory) -> tuple[Workspace, Path]:
    ws = make_workspace("check")
    require(ws.generate())
    pristine = tmp_path_factory.mktemp("check-pristine")
    for name in RESTORED:
        shutil.copytree(ws.root / name, pristine / name, symlinks=True)
    return ws, pristine


@pytest.fixture
def ws(shared) -> Workspace:
    workspace, pristine = shared
    for name in RESTORED:
        shutil.rmtree(workspace.root / name)
        shutil.copytree(pristine / name, workspace.root / name, symlinks=True)
    workspace.steps.clear()
    return workspace


# --------------------------------------------------------------------------- helpers


def check(ws: Workspace, layer: str) -> Step:
    return ws.run("uv", "run", layer, "generate", "--check")


def task_check(ws: Workspace) -> Step:
    return ws.run("uv", "run", "task", "check")


def owned_folders(ws: Workspace, layer: str) -> list[Path]:
    """Package folders whose README carries ``layer``'s generator marker."""
    heading = f"# Generated by `uv run {layer} generate`"
    found = sorted(
        readme.parent
        for readme in (ws.root / "models").glob("*/*/README.md")
        if readme.read_text(encoding="utf-8").splitlines()[:1] == [heading]
    )
    assert found, f"no folder under models/ carries the {layer} marker"
    return found


def generated_file(ws: Workspace, layer: str, suffix: str = ".sql") -> Path:
    files = sorted(p for folder in owned_folders(ws, layer) for p in folder.glob(f"*{suffix}"))
    assert files, f"{layer} owns no {suffix} file"
    return files[0]


def rel(ws: Workspace, path: Path) -> str:
    return path.relative_to(ws.root).as_posix()


def normalize(ws: Workspace, reported: str) -> str:
    reported = reported.rstrip(":,;").rstrip("/")
    if reported.startswith("./"):
        reported = reported[2:]
    path = Path(reported)
    if path.is_absolute() and path.is_relative_to(ws.root):
        return path.relative_to(ws.root).as_posix()
    return reported


def report(ws: Workspace, step: Step) -> set[tuple[str, str]]:
    """(kind, path) of every status line in ``step``'s output."""
    found = set()
    for line in step.output.splitlines():
        match = STATUS.match(line)
        if match:
            found.add((match.group(1), normalize(ws, match.group(2))))
    return found


def paths(found: set[tuple[str, str]], kind: str | None = None) -> set[str]:
    return {path for k, path in found if kind is None or k == kind}


def section(step: Step, ws: Workspace, path: str) -> list[str]:
    """The output lines under ``path``'s status line, up to the next status line or the summary."""
    lines = step.output.splitlines()
    start = next(
        (i for i, line in enumerate(lines) if (m := STATUS.match(line)) and normalize(ws, m.group(2)) == path),
        None,
    )
    assert start is not None, f"no status line for {path}:\n{step.output[-3000:]}"
    out = [lines[start]]
    for line in lines[start + 1 :]:
        if STATUS.match(line) or "task generate" in line:
            break
        out.append(line)
    return out


def drifted(step: Step, what: str) -> None:
    assert step.returncode == 1, f"{what}: expected exit 1, got {step.returncode}:\n{step.output[-3000:]}"
    assert "Traceback" not in step.output, step.output[-3000:]


def clean(step: Step, what: str) -> None:
    assert step.returncode == 0, f"{what}: expected exit 0, got {step.returncode}:\n{step.output[-3000:]}"
    assert step.output.strip() == "", f"{what}: a clean check printed:\n{step.output[-3000:]}"


def summary_names_generate(step: Step) -> None:
    assert "task generate" in step.output, f"no summary naming `task generate`:\n{step.output[-3000:]}"


def edit_by_hand(path: Path) -> None:
    path.write_text(path.read_text(encoding="utf-8") + f"\n-- {EDIT_MARK}\n", encoding="utf-8")


def contract_path(ws: Workspace) -> Path:
    found = sorted((ws.root / "contracts").rglob("*.yaml"))
    assert found, "no contract under contracts/"
    return found[0]


def edit_yaml(path: Path, change) -> None:
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    change(document)
    path.write_text(yaml.safe_dump(document, sort_keys=False, allow_unicode=True), encoding="utf-8")


def snapshot(ws: Workspace) -> tuple[dict[str, str], set[str]]:
    """File hashes of the tree, and every folder under models/ (an empty one included)."""
    folders = {rel(ws, p) for p in (ws.root / "models").rglob("*") if p.is_dir()}
    return ws.tree(), folders


def verdicts(step: Step) -> dict[str, set[str]]:
    """layer -> the verdicts ('pass' or 'fail') its lines in ``task check``'s output give."""
    fail = re.compile(r"\b(fail|failed|failing|failure)\b", re.IGNORECASE)
    passed = re.compile(r"\b(pass|passed|ok|clean)\b", re.IGNORECASE)
    found: dict[str, set[str]] = {layer: set() for layer in LAYERS}
    for line in step.output.splitlines():
        # go-task echoes each command it runs as `task: [check] <command>`.
        if line.startswith("task:") or line[:1] in ("+", "-", "@", " ") or STATUS.match(line):
            continue
        if "models/" in line:
            continue
        for layer in LAYERS:
            if re.search(rf"\b{layer}\b", line, re.IGNORECASE):
                if fail.search(line):
                    found[layer].add("fail")
                elif passed.search(line):
                    found[layer].add("pass")
    return found


def assert_verdicts(step: Step, expected: dict[str, str]) -> None:
    found = verdicts(step)
    assert found == {layer: {verdict} for layer, verdict in expected.items()}, (
        f"expected one pass/fail line per layer {expected}, read {found}:\n{step.output[-4000:]}"
    )


