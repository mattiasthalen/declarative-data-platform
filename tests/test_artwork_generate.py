"""The artwork generator writes and owns `assets/` (story #38: AC1, AC2, EC1).

Each test runs ``uv run artwork generate`` (with or without ``--check``) or a task as a
subprocess, in one shared throwaway copy of the repo whose ``assets/`` is put back before every
test. The report's interface is the layers' (``test_generate_check.py``): one line per drifted
path, ``changed <path>``, ``missing <path>`` or ``stale <path>``, relative to the repo root, a
diff under a changed file; exit 0 and no output when clean, 1 on drift, 2 on a refused folder.

- ``-k artwork_generate``: AC1. ``-k artwork_drift``: AC2, EC1.
"""

from __future__ import annotations

import re
import shutil
import tomllib
from pathlib import Path

import pytest
import yaml
from harness import REPO, Step, Workspace, require

ASSETS = "assets"
HERO = "assets/hero.svg"
MARKER = "# Generated by `uv run artwork generate`"
STATUS = re.compile(r"^(changed|missing|stale)\s+(\S+)")


@pytest.fixture(scope="module")
def shared(make_workspace, tmp_path_factory) -> tuple[Workspace, Path]:
    ws = make_workspace("artwork")
    require(ws.run("uv", "run", "artwork", "generate"))
    pristine = tmp_path_factory.mktemp("artwork-pristine") / ASSETS
    shutil.copytree(ws.root / ASSETS, pristine)
    return ws, pristine


@pytest.fixture
def ws(shared) -> Workspace:
    workspace, pristine = shared
    shutil.rmtree(workspace.root / ASSETS, ignore_errors=True)
    shutil.copytree(pristine, workspace.root / ASSETS)
    workspace.steps.clear()
    return workspace


def generate(ws: Workspace, *flags: str) -> Step:
    return ws.run("uv", "run", "artwork", "generate", *flags)


def normalize(ws: Workspace, reported: str) -> str:
    reported = reported.rstrip(":,;").rstrip("/")
    reported = reported.removeprefix("./")
    path = Path(reported)
    if path.is_absolute() and path.is_relative_to(ws.root):
        return path.relative_to(ws.root).as_posix()
    return reported


def report(ws: Workspace, step: Step) -> set[tuple[str, str]]:
    """(kind, path) of every status line in ``step``'s output."""
    return {
        (match.group(1), normalize(ws, match.group(2)))
        for line in step.output.splitlines()
        if (match := STATUS.match(line))
    }


def files(ws: Workspace) -> dict[str, bytes]:
    folder = ws.root / ASSETS
    return {p.relative_to(ws.root).as_posix(): p.read_bytes() for p in sorted(folder.rglob("*")) if p.is_file()}


def drifted(step: Step, what: str) -> None:
    assert step.returncode == 1, f"{what}: expected exit 1, got {step.returncode}:\n{step.output[-3000:]}"
    assert "Traceback" not in step.output, step.output[-3000:]


def clean(step: Step, what: str) -> None:
    assert step.returncode == 0, f"{what}: expected exit 0, got {step.returncode}:\n{step.output[-3000:]}"
    assert step.output.strip() == "", f"{what}: a clean check printed:\n{step.output[-3000:]}"


# --------------------------------------------------------------------------- AC1


def test_artwork_generate_writes_assets(make_workspace):
    """AC1: in a copy with no `assets/`, `uv run artwork generate` exits 0 and writes
    `assets/README.md`, whose first line is the generator's marker, and `assets/hero.svg`, the
    same bytes as the committed file; `--check` then exits 0 and prints nothing."""
    ws = make_workspace("artwork-fresh")
    shutil.rmtree(ws.root / ASSETS, ignore_errors=True)
    require(generate(ws))
    readme = ws.root / ASSETS / "README.md"
    assert readme.is_file(), "artwork generate wrote no assets/README.md"
    first = readme.read_text(encoding="utf-8").splitlines()[:1]
    assert first == [MARKER], f"assets/README.md's first line is {first}, expected {MARKER!r}"
    hero = ws.root / HERO
    assert hero.is_file(), "artwork generate wrote no assets/hero.svg"
    committed = REPO / HERO
    assert committed.is_file(), "assets/hero.svg is not committed in the repo"
    assert hero.read_bytes() == committed.read_bytes(), "artwork generate writes an assets/hero.svg unlike the committed one"
    clean(generate(ws, "--check"), "artwork generate --check after generate")
    clean(generate(ws, "--check"), "artwork generate --check run twice")


def test_artwork_generate_in_tasks(ws):
    """AC1: `artwork` is a script of the project; `task generate` runs `uv run artwork generate`
    and `task check` checks `artwork` beside conform, integrate and serve, so a hand edit to
    `assets/hero.svg` fails `task check` (naming the file and `artwork`) and `task generate`
    puts it back."""
    scripts = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))["project"]["scripts"]
    assert "artwork" in scripts, f"pyproject.toml's [project.scripts] has no artwork: {sorted(scripts)}"

    tasks = yaml.safe_load((REPO / "Taskfile.yml").read_text(encoding="utf-8"))["tasks"]
    commands = " \n".join(str(c) for c in tasks["generate"]["cmds"])
    assert "uv run artwork generate" in commands, f"task generate does not run `uv run artwork generate`:\n{commands}"

    clean_run = ws.run("uv", "run", "task", "check")
    assert clean_run.returncode == 0, f"task check fails on a clean copy:\n{clean_run.output[-3000:]}"
    for layer in ("conform", "integrate", "serve", "artwork"):
        assert f"{layer}: pass" in clean_run.output, f"task check printed no `{layer}: pass`:\n{clean_run.output}"

    hero = ws.root / HERO
    hero.write_text(hero.read_text(encoding="utf-8").replace("</svg>", "<!-- hand edit --></svg>"), encoding="utf-8")
    failed = ws.run("uv", "run", "task", "check")
    assert failed.returncode != 0, f"task check passed with assets/hero.svg edited by hand:\n{failed.output[-3000:]}"
    assert ("changed", HERO) in report(ws, failed), f"task check did not report `changed {HERO}`:\n{failed.output[-3000:]}"
    assert "artwork: fail" in failed.output, f"task check printed no `artwork: fail`:\n{failed.output[-3000:]}"
    for layer in ("conform", "integrate", "serve"):
        assert f"{layer}: pass" in failed.output, f"a hand edit to assets/ failed {layer}:\n{failed.output[-3000:]}"

    require(ws.run("uv", "run", "task", "generate"))
    assert "<!-- hand edit -->" not in hero.read_text(encoding="utf-8"), "task generate left the hand edit"
    require(ws.run("uv", "run", "task", "check"))


# --------------------------------------------------------------------------- AC2, EC1


def test_artwork_drift_changed_byte(ws):
    """AC2, EC1: one byte changed in `assets/hero.svg` makes `--check` exit 1 with
    `changed assets/hero.svg` and a diff showing the change; the check writes nothing."""
    hero = ws.root / HERO
    data = bytearray(hero.read_bytes())
    at = data.index(b"<title>") + len(b"<title>")
    data[at : at + 1] = b"X" if data[at : at + 1] != b"X" else b"Y"
    hero.write_bytes(bytes(data))
    before = files(ws)
    step = generate(ws, "--check")
    drifted(step, "a byte changed in assets/hero.svg")
    assert report(ws, step) == {("changed", HERO)}, f"expected only `changed {HERO}`:\n{step.output[-3000:]}"
    lines = step.output.splitlines()
    start = next(i for i, line in enumerate(lines) if STATUS.match(line))
    diff = [line for line in lines[start + 1 :] if line.startswith(("+", "-")) and not line.startswith(("+++", "---"))]
    assert any("<title>" in line for line in diff), f"no diff line shows the changed <title>:\n{step.output[-3000:]}"
    assert files(ws) == before, "artwork generate --check changed assets/"


def test_artwork_drift_stale_file(ws):
    """AC2: a file added to `assets/` makes `--check` exit 1 with `stale assets/x.txt`; the next
    `generate` removes it and `--check` is clean."""
    (ws.root / ASSETS / "x.txt").write_text("added by hand\n", encoding="utf-8")
    step = generate(ws, "--check")
    drifted(step, "a file added to assets/")
    assert report(ws, step) == {("stale", "assets/x.txt")}, f"expected only `stale assets/x.txt`:\n{step.output[-3000:]}"
    assert (ws.root / ASSETS / "x.txt").exists(), "artwork generate --check removed the stale file"
    require(generate(ws))
    assert not (ws.root / ASSETS / "x.txt").exists(), "artwork generate left assets/x.txt in place"
    clean(generate(ws, "--check"), "artwork generate --check after generate removed the stale file")


def test_artwork_drift_missing_file(ws):
    """AC2: `assets/hero.svg` deleted makes `--check` exit 1 with `missing assets/hero.svg`; the
    next `generate` writes it back."""
    (ws.root / HERO).unlink()
    step = generate(ws, "--check")
    drifted(step, "assets/hero.svg deleted")
    assert report(ws, step) == {("missing", HERO)}, f"expected only `missing {HERO}`:\n{step.output[-3000:]}"
    assert not (ws.root / HERO).exists(), "artwork generate --check wrote assets/hero.svg"
    require(generate(ws))
    clean(generate(ws, "--check"), "artwork generate --check after generate wrote the file back")


def test_artwork_drift_unmarked_folder(ws):
    """AC2: an `assets/` without its marker README is refused: `--check` and `generate` both
    exit 2 naming `assets`, with no traceback, and `generate` writes nothing there."""
    (ws.root / ASSETS / "README.md").unlink()
    before = files(ws)
    for flags in (("--check",), ()):
        step = generate(ws, *flags)
        what = f"artwork generate {' '.join(flags)}".strip()
        assert step.returncode == 2, f"{what} on an unmarked assets/: expected exit 2, got {step.returncode}:\n{step.output[-3000:]}"
        assert "assets" in step.output, f"{what}'s refusal does not name assets:\n{step.output[-3000:]}"
        assert "Traceback" not in step.output, step.output[-3000:]
        assert files(ws) == before, f"{what} changed the unmarked assets/"
